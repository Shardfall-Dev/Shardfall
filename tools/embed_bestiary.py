#!/usr/bin/env python3
"""Embed the bestiary pack into the single-file build.

usage: python3 tools/embed_bestiary.py [assets/bestiary/Shardfall_Bestiary_v1.0.0.zip] [src/bestiary-art.js]

Reads manifest.json and every atlas straight from the versioned ZIP (no extraction needed),
checks each PNG is a 5x8 grid of manifest-sized cells, and writes src/bestiary-art.js:
  const BESTIARY = { version, frame, rows, columns, animations, mobs, src: { id: dataURI } };
The PNG bytes are embedded unchanged, so alpha, the Lich Lord's rim and its glints stay as painted.
"""
import base64, json, struct, sys, zipfile

ZIP = sys.argv[1] if len(sys.argv) > 1 else 'assets/bestiary/Shardfall_Bestiary_v1.0.0.zip'
OUT = sys.argv[2] if len(sys.argv) > 2 else 'src/bestiary-art.js'
BASE = 'assets/bestiary/v1/'


def png_size(b):
    if b[:8] != b'\x89PNG\r\n\x1a\n' or b[12:16] != b'IHDR':
        raise SystemExit('not a PNG')
    w, h = struct.unpack('>II', b[16:24])
    return w, h, b[25]  # colour type


with zipfile.ZipFile(ZIP) as z:
    man = json.loads(z.read(BASE + 'manifest.json'))
    fw, fh = man['frame']['width'], man['frame']['height']
    cols, rows = len(man['columns']), len(man['rows'])
    src, bad = {}, []
    for mob in man['mobs']:
        b = z.read(BASE + mob['atlas'])
        w, h, ct = png_size(b)
        if (w, h) != (fw * cols, fh * rows):
            bad.append(f"{mob['id']}: {w}x{h}, expected {fw * cols}x{fh * rows}")
        if ct not in (3, 6) and b'tRNS' not in b[:4096]:
            bad.append(f"{mob['id']}: no alpha channel")
        src[mob['id']] = 'data:image/png;base64,' + base64.b64encode(b).decode()
    if bad:
        raise SystemExit('bestiary pack rejected:\n  ' + '\n  '.join(bad))

data = {k: man[k] for k in ('version', 'frame', 'rows', 'columns', 'animations', 'mobs')}
data['src'] = src
with open(OUT, 'w') as f:
    f.write('/* Shardfall bestiary v%s: generated by tools/embed_bestiary.py from %s. Do not edit by hand. */\n' % (man['version'], ZIP.split('/')[-1]))
    f.write('const BESTIARY=' + json.dumps(data, separators=(',', ':')) + ';\n')
print(f"wrote {OUT}: {len(src)} sheets, v{man['version']}")
