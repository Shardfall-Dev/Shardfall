#!/usr/bin/env python3
"""Emit the <script> block that embeds the sound pack in the standalone build.

Reads assets/audio/manifest.json and every WAV it lists (paths relative to
assets/audio/), and writes one script that defines:

  SFX_MANIFEST  the manifest as shipped, plus "peak" (seconds to the loudest
                10 ms window of each take, used to land swings on contact) and
                "dur" (take length in seconds), both keyed by relative path
  SFX_DATA      base64 WAV bytes keyed by the exact relative path (offline build only)
  MUSIC         the Saltmarsh soundtrack: per track the web copy (AAC) and the MP3 master,
                as paths relative to the page, plus the loop end in seconds

Usage: python3 tools/embed_audio.py [assets/audio] [--hosted] > out.js
  default    the offline single file: every take is embedded (large, about 19 MB)
  --hosted   the web build: only the manifest; takes are fetched from assets/audio/web/
             (see tools/encode_web_audio.sh) when first needed
The MIDI bank and preview MP3 are not part of the game and are never embedded.
"""
import base64
import json
import os
import sys
import wave
from array import array


def analyse(path):
    with wave.open(path, 'rb') as w:
        ch, width, rate, n = w.getnchannels(), w.getsampwidth(), w.getframerate(), w.getnframes()
        raw = w.readframes(n)
    if width != 2:
        raise SystemExit(f'{path}: expected 16-bit PCM, got {width * 8}-bit')
    a = array('h'); a.frombytes(raw)
    if sys.byteorder == 'big':
        a.byteswap()
    if ch > 1:
        a = a[::ch]
    win = max(1, rate // 100)
    best, at = -1, 0
    for i in range(0, len(a), win):
        seg = a[i:i + win]
        e = sum(v * v for v in seg)
        if e > best:
            best, at = e, i
    return round((at + win / 2) / rate, 4), round(len(a) / rate, 4)


def music(root):
    sdir = os.path.join(root, '..', 'music', 'v1.0.0')
    with open(os.path.join(sdir, 'soundtrack.json'), encoding='utf-8') as f:
        st = json.load(f)
    out = {}
    for t in st['tracks']:
        web = 'assets/audio/web/music/%s.m4a' % t['id']
        if not os.path.isfile(os.path.join(root, 'web', 'music', t['id'] + '.m4a')):
            raise SystemExit(f'missing {web}: run tools/encode_web_audio.sh')
        out[t['id']] = {'title': t['title'], 'web': web, 'mp3': 'assets/music/v1.0.0/' + t['mp3'], 'loopEnd': t['loop_end_seconds']}
    return out


def main():
    args = [a for a in sys.argv[1:] if not a.startswith('--')]
    hosted = '--hosted' in sys.argv
    root = args[0] if args else os.path.join(os.path.dirname(__file__), '..', 'assets', 'audio')
    with open(os.path.join(root, 'manifest.json'), encoding='utf-8') as f:
        man = json.load(f)
    data, peak, dur = {}, {}, {}
    for ev, e in man['events'].items():
        for rel in e['files']:
            p = os.path.join(root, rel)
            if not os.path.isfile(p):
                raise SystemExit(f'missing {rel} for {ev}')
            if hosted:
                w = os.path.join(root, 'web', os.path.splitext(rel)[0] + '.m4a')
                if not os.path.isfile(w):
                    raise SystemExit(f'missing web copy of {rel}: run tools/encode_web_audio.sh')
            else:
                with open(p, 'rb') as f:
                    data[rel] = base64.b64encode(f.read()).decode('ascii')
            peak[rel], dur[rel] = analyse(p)
    man = dict(man, peak=peak, dur=dur)
    out = sys.stdout
    out.write('<script>\n/* Shardfall sound pack v%s: generated by tools/embed_audio.py from assets/audio. Do not edit. */\n' % man.get('releaseVersion', '?'))
    out.write('var SFX_MANIFEST = ' + json.dumps(man, separators=(',', ':')) + ';\n')
    out.write('var MUSIC = ' + json.dumps(music(root), separators=(',', ':')) + ';\n')
    if hosted:
        out.write('var SFX_WEB = "assets/audio/web/";\n</script>\n')
        print(f'hosted build: {len(peak)} takes for {len(man["events"])} events load from assets/audio/web/', file=sys.stderr)
        return
    out.write('var SFX_DATA = {\n')
    out.write(',\n'.join(json.dumps(k) + ':"' + v + '"' for k, v in data.items()))
    out.write('};\n</script>\n')
    print(f'embedded {len(data)} takes for {len(man["events"])} events', file=sys.stderr)


if __name__ == '__main__':
    main()
