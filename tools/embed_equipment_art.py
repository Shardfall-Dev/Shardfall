#!/usr/bin/env python3
"""Embed the Medieval Equipment Art v1 pack into the game as src/equipment-art.js.

usage: python3 tools/embed_equipment_art.py [ZIP] > src/equipment-art.js
       (default ZIP: asset-packs/medieval-equipment-art-v1/Shardfall_Medieval_Equipment_Art_v1.zip)

Reads the pieces and masks from the ZIP (never extracts it to disk), packs them into one art atlas and one
matching mask atlas, and writes GEAR_ART: atlas data URIs, a rect per piece id and the manifest's material
channels. Needs Pillow.

Mask channels (from the pack): R = primary material weight, G = secondary material weight, B = fixed (never
recoloured), A = source alpha. The pack's masks were estimated automatically. This tool applies a few
documented corrections so paint that is not the material stays fixed (see CORRECTIONS below); the counts of
moved pixels are written into the output so the corrections can be reviewed.
"""
import base64, colorsys, io, json, sys, zipfile
from PIL import Image

ZIP = sys.argv[1] if len(sys.argv) > 1 else 'asset-packs/medieval-equipment-art-v1/Shardfall_Medieval_Equipment_Art_v1.zip'
ROOT = 'Shardfall_Medieval_Equipment_Art_v1/'
SCALE = 0.6        # pieces are drawn on the paper doll at about 0.55 of their source size; 0.6 keeps them crisp

z = zipfile.ZipFile(ZIP)
man = json.loads(z.read(ROOT + 'manifest.json'))
img = lambda p: Image.open(io.BytesIO(z.read(ROOT + p))).convert('RGBA')

# corrections, applied to the primary (R) channel only: such pixels move to fixed (B)
#  - metal primary: saturated paint (heraldry, leather straps, wooden grips the estimator called metal) is not metal
#  - hide or cloth primary: bright unsaturated pixels are metal buckles, rivets or bow strings, not leather or cloth
#  - cloth primary: gold embroidery and trim keep their colour when the cloth is dyed
#  - wood primary: the pale bow string is not wood
def correct(prim, r, g, b, w):
    h, l, s = colorsys.rgb_to_hls(r / 255, g / 255, b / 255)
    if prim == 'metal' and s > .38 and l > .12: return True
    if prim in ('hide', 'cloth', 'wood') and s < .14 and l > .52: return True
    if prim == 'cloth' and .09 < h < .16 and s > .45 and l > .38: return True
    return False

items, tiles = {}, []
for it in man['items']:
    a, m = img(it['art']), img(it['mask'])
    if a.size != m.size: sys.exit(f"size mismatch for {it['id']}: {a.size} vs {m.size}")
    moved = 0
    if it['primary'] not in ('fixed', None):
        px, mp = a.load(), m.load()
        for y in range(a.height):
            for x in range(a.width):
                r, g, b, al = px[x, y]
                if not al: continue
                R, G, B, A = mp[x, y]
                if R > 40 and correct(it['primary'], r, g, b, R): mp[x, y] = (0, G, min(255, B + R), A); moved += 1
    w, h = max(1, round(a.width * SCALE)), max(1, round(a.height * SCALE))
    a, m = a.resize((w, h), Image.LANCZOS), m.resize((w, h), Image.NEAREST)
    tiles.append((it['id'], a, m))
    items[it['id']] = {'slot': it['slot'], 'prim': it['primary'], 'sec': it['secondary'], 'side': it['variant'], 'fixedPx': moved}

# shelf packing, tallest first, 1 px gutter
tiles.sort(key=lambda t: -t[1].height)
W = 1024; x = y = sh = 0; rect = {}
for id_, a, m in tiles:
    if x + a.width > W: x, y, sh = 0, y + sh + 1, 0
    rect[id_] = [x, y, a.width, a.height]; x += a.width + 1; sh = max(sh, a.height)
H = y + sh
art, mask = Image.new('RGBA', (W, H)), Image.new('RGBA', (W, H))
for id_, a, m in tiles: art.paste(a, tuple(rect[id_][:2])); mask.paste(m, tuple(rect[id_][:2]))
def uri(im):
    b = io.BytesIO(); im.save(b, 'PNG', optimize=True); return 'data:image/png;base64,' + base64.b64encode(b.getvalue()).decode()

out = {'version': man['version'], 'status': man['status'], 'scale': SCALE, 'w': W, 'h': H, 'rect': rect, 'item': items,
       'art': uri(art), 'mask': uri(mask)}
print('/* Medieval Equipment Art v' + man['version'] + ': generated by tools/embed_equipment_art.py from')
print('   asset-packs/medieval-equipment-art-v1/Shardfall_Medieval_Equipment_Art_v1.zip. Do not edit by hand. */')
print('const GEAR_ART = ' + json.dumps(out, separators=(',', ':')) + ';')
